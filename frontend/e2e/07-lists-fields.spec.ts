test('admin defines a required field and the backend enforces it on create', async ({ page }) => {
  await login(page)
  await page.getByRole('link', { name: 'Lists & Views' }).click()
  await page.getByRole('tab', { name: 'Custom fields' }).click()
  await page.getByLabel('Field entity').selectOption('company')
  await page.getByLabel('Field label').fill('Compliance contact')
  await page.getByLabel('Required').check()
  await page.getByRole('button', { name: 'Add field' }).click()
  await expect(page.getByRole('cell', { name: 'Compliance contact' })).toBeVisible()
  await page.getByRole('link', { name: 'Companies' }).click()
  await page.getByRole('button', { name: 'New entity' }).click()
  await page.getByLabel('Name', { exact: true }).fill('E2E Required Field Holdings LLC')
  await page.getByRole('button', { name: 'Create entity' }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('Compliance contact is required')
  // retire it so the rest of the suite is unaffected; retired fields keep their data but stop applying
  await page.keyboard.press('Escape')
  await page.getByRole('link', { name: 'Lists & Views' }).click()
  await page.getByRole('tab', { name: 'Custom fields' }).click()
  await page.getByRole('row', { name: /Compliance contact/ }).getByRole('button', { name: 'Retire' }).click()
  await expect(page.getByRole('row', { name: /Compliance contact/ }).getByText('retired')).toBeVisible()
})

