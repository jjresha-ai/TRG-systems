import { expect, test } from '@playwright/test'
import { login } from './helpers'

const count = async (page: import('@playwright/test').Page) => Number((await page.getByTestId('result-count').locator('b').innerText()).replace(/,/g, ''))

async function addCondition(page: import('@playwright/test').Page, field: string, operator: string, value?: string, valueLabel = 'Value') {
  await page.getByRole('button', { name: 'Condition', exact: true }).first().click()
  const row = page.getByTestId('condition').last()
  await row.getByLabel('Field').selectOption({ label: field })
  await row.getByLabel('Operator').selectOption({ label: operator })
  if (value !== undefined) await row.getByLabel(valueLabel).fill(value)
}

test('query builder: conditions narrow results live and OR widens them', async ({ page }) => {
  await login(page)
  await page.getByRole('link', { name: 'Lists & Views' }).click()
  await expect(page.getByTestId('results')).toBeVisible()
  const all = await count(page)
  expect(all).toBeGreaterThan(100)
  await addCondition(page, 'Loan maturity', 'is within next (days)', '365', 'Days')
  await expect.poll(() => count(page)).toBeLessThan(all)
  const maturing = await count(page)
  await addCondition(page, 'Property type', 'is')
  await page.getByTestId('condition').last().getByLabel('Value').selectOption('industrial')
  await expect.poll(() => count(page)).toBeLessThan(maturing)
  await page.getByLabel('Match operator').selectOption('or')
  await expect.poll(() => count(page)).toBeGreaterThan(maturing)
})

