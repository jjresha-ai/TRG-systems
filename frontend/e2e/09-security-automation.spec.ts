import { expect, test } from '@playwright/test'
import { login } from './helpers'

const tag = () => Math.random().toString(36).slice(2, 8)

test('admin sees users, roles and the role matrix; changing a role is enforced', async ({ page }) => {
  const t = tag()
  await login(page)
  await page.getByRole('link', { name: 'Admin & Audit' }).click()
  await expect(page.getByTestId('users')).toBeVisible()
  await expect(page.getByText('What each role can do')).toBeVisible()
  await page.getByRole('button', { name: 'Add user' }).click()
  await page.getByLabel('User name').fill(`E2E Reader ${t}`)
  await page.getByLabel('User email').fill(`reader${t}@e2e.test`)
  await page.getByLabel('User role').selectOption('read_only')
  await page.getByLabel('User password').fill('longpass1')
  await page.getByRole('button', { name: 'Create user' }).click()
  await expect(page.getByTestId('users').getByText(`reader${t}@e2e.test`)).toBeVisible()
  await page.getByLabel(`Role for E2E Reader ${t}`).selectOption('broker')
  await expect(page.getByLabel(`Role for E2E Reader ${t}`)).toHaveValue('broker')
})

