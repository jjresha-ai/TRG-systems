test('automation: build a rule, run it twice, and it never repeats', async ({ page }) => {
  const t = tag()
  await login(page)
  await page.getByRole('link', { name: 'Automation' }).click()
  await page.getByRole('button', { name: 'New rule' }).click()
  await page.getByLabel('Rule name').fill(`E2E rule ${t}`)
  await page.getByLabel('Rule entity').selectOption('contact')
  await page.getByLabel('Trigger').selectOption('scheduled')
  await page.getByLabel('Only if conditions match').check()
  await page.getByRole('button', { name: 'Condition', exact: true }).click()
  await page.getByTestId('condition').last().getByLabel('Field').selectOption({ label: 'Tags' })
  await page.getByTestId('condition').last().getByLabel('Operator').selectOption({ label: 'contains' })
  await page.getByTestId('condition').last().getByLabel('Value').fill('vip')
  await page.getByLabel('Task subject').fill(`E2E follow up ${t} for {name}`)
  await page.getByRole('button', { name: 'Create rule' }).click()
  const card = page.getByTestId('rules').locator('div.rounded-lg', { hasText: `E2E rule ${t}` }).first()
  await expect(card).toBeVisible()
  await card.getByRole('button', { name: 'Run now' }).click()
  const matched = Number(await page.getByTestId('rule-matched').innerText())
  expect(matched).toBeGreaterThan(0)
  await expect(page.getByRole('dialog')).toContainText('actions taken')
  await page.keyboard.press('Escape')
  await card.getByRole('button', { name: 'Run now' }).click()
  await expect(page.getByRole('dialog')).toContainText('0 actions taken')
})

