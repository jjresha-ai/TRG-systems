test('API tokens are shown once, scoped to the role, and revocable', async ({ page }) => {
  const t = tag()
  await login(page, 'tyler@1880capital.com')
  await page.getByRole('link', { name: 'Admin & Audit' }).click()
  await expect(page.getByRole('tab', { name: 'Users & roles' })).toHaveCount(0)
  await expect(page.getByLabel('delete')).toHaveCount(0)
  await page.getByLabel('Token name').fill(`Integration ${t}`)
  await page.getByRole('button', { name: 'Create token' }).click()
  const code = page.getByRole('status').locator('code')
  await expect(code).toContainText('trg_')
  const token = await code.innerText()
  const res = await page.request.get('/api/contacts?limit=1', { headers: { Authorization: `Bearer ${token}` } })
  expect(res.status()).toBe(200)
  const denied = await page.request.post('/api/contacts', { data: { first_name: 'No', last_name: 'Scope' }, headers: { Authorization: `Bearer ${token}` } })
  expect(denied.status()).toBe(403)
  await page.getByRole('row', { name: new RegExp(`Integration ${t}`) }).getByRole('button', { name: 'Revoke' }).click()
  await expect(page.getByRole('row', { name: new RegExp(`Integration ${t}`) }).getByText('revoked')).toBeVisible()
  expect((await page.request.get('/api/contacts?limit=1', { headers: { Authorization: `Bearer ${token}` } })).status()).toBe(401)
})

