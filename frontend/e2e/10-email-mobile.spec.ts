test('field mode: a note taken offline is queued and syncs when the connection returns', async ({ page, context }) => {
  const t = tag()
  await login(page)
  await page.goto('/m')
  await page.getByLabel('Find a record').fill('Edward Morales')
  await page.getByRole('button', { name: /Edward Morales/ }).first().click()
  await context.setOffline(true)
  await expect(page.getByTestId('net-status')).toContainText('Offline')
  await page.getByLabel('Quick text').fill(`Offline note ${t}`)
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByTestId('flash')).toContainText('Offline: queued')
  await expect(page.getByTestId('queue-count')).toContainText('1 waiting')
  await context.setOffline(false)
  await expect(page.getByTestId('queue-count')).toHaveCount(0, { timeout: 15000 })
  await page.goto('/contacts/1')
  await expect(page.getByText(`Offline note ${t}`)).toBeVisible()
})
