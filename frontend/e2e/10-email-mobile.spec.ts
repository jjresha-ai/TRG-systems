import { expect, test } from '@playwright/test'
import { login } from './helpers'

const tag = () => Math.random().toString(36).slice(2, 8)

test('email inbox shows seeded mail, privacy controls and the provider notice', async ({ page }) => {
  await login(page)
  await page.getByRole('link', { name: /^Email/  }).click()
  await expect(page.getByTestId('provider-notice')).toContainText('Sending from the CRM is off')
  await expect(page.getByTestId('mail-row').first()).toBeVisible()
  expect(await page.getByTestId('mail-row').count()).toBeGreaterThan(5)
  const sel = page.getByTestId('mail-row').first().getByRole('combobox')
  await sel.selectOption('team_full')
  await expect(sel).toHaveValue('team_full')
  await page.getByRole('button', { name: 'Needs a home' }).click()
  await expect(page.getByTestId('mail-row').first().getByText('Not linked to any record')).toBeVisible()
})

test('exclusion rules are added and removed', async ({ page }) => {
  const t = tag()
  await login(page)
  await page.goto('/inbox')
  await page.getByRole('tab', { name: 'Privacy rules' }).click()
  await page.getByLabel('Rule value').fill(`${t}.example`)
  await page.getByRole('button', { name: 'Add rule' }).click()
  await expect(page.getByTestId('rules').getByText(`${t}.example`)).toBeVisible()
  await page.getByLabel(`Remove ${t}.example`).click()
  await expect(page.getByTestId('rules').getByText(`${t}.example`)).toHaveCount(0)
})

test('bulk email can be prepared and checked but not sent until a provider is chosen', async ({ page }) => {
  const t = tag()
  await login(page)
  await page.goto('/inbox')
  await page.getByRole('tab', { name: 'Templates & bulk' }).click()
  await expect(page.getByTestId('template').first()).toBeVisible()
  await page.getByLabel('Bulk name').fill(`E2E blast ${t}`)
  await page.getByLabel('Bulk template').selectOption({ index: 1 })
  await page.getByLabel('Bulk list').selectOption({ index: 1 })
  await page.getByRole('button', { name: 'Prepare and check recipients' }).click()
  await expect(page.getByTestId('bulk-result')).toContainText('Eligible')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.getByTestId('send-blocked')).toContainText('No mail provider')
  await expect(page.getByTestId('bulk-row').filter({ hasText: `E2E blast ${t}` })).toBeVisible()
})

