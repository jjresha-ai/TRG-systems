test('field mode: quick note saves, caller lookup matches, starred list shows', async ({ page }) => {
  const t = tag()
  await login(page)
  await page.getByRole('link', { name: 'Field Mode' }).click()
  await page.getByLabel('Find a record').fill('Edward Morales')
  await page.getByRole('button', { name: /Edward Morales/ }).first().click()
  await expect(page.getByTestId('picked')).toContainText('Edward Morales')
  await page.getByLabel('Quick text').fill(`Walked the site ${t}`)
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByTestId('flash')).toContainText('Saved to')
  await page.goto('/contacts/1')
  await expect(page.getByText(`Walked the site ${t}`)).toBeVisible()
  await page.goto('/m')
  await page.getByLabel('Caller phone').fill('(619) 857-9628')
  await expect(page.getByTestId('caller-result')).toContainText('Edward Morales')
  await page.getByLabel('Caller phone').fill('(310) 555-0000')
  await expect(page.getByTestId('caller-result')).toContainText('No match')
  await expect(page.getByTestId('starred').locator('> div').first()).toBeVisible()
})

